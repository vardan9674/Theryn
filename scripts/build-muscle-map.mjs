// Builds src/lib/muscleMap.generated.js — the exercise-name → muscles lookup the
// link page uses to draw a heat map after a workout.
//
// Why generated and committed rather than fetched: public/exercises.json is 978 KB,
// and the link page is opened on a phone, often on mobile data, by a client who may
// not be signed in. The map below is a few tens of KB of muscle data only — no
// instructions, no image paths — so it ships in the bundle and cannot fail to load
// at the one moment it is needed.
//
// Run: node scripts/build-muscle-map.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { buildLibrary } from "../src/lib/exerciseLibrary.js";
import { mapKeys } from "../src/lib/muscleHeat.js";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, "..");

const raw = JSON.parse(fs.readFileSync(path.join(root, "public/exercises.json"), "utf8"));
const { aliases, synonyms } = JSON.parse(fs.readFileSync(path.join(here, "theryn-exercise-aliases.json"), "utf8"));

const library = buildLibrary(raw);
const byId = new Map(library.map((e) => [e.id, e]));

// group list per exercise, main muscle first
const musclesOf = (e) => [e.group, ...e.helperGroups];

/**
 * key → muscle groups. Several keys can point at the same exercise: its own name,
 * Theryn's name for it, and the reduced forms mapKeys() produces (a name with the
 * equipment and grip words taken off). Equipment is deliberately *not* kept apart
 * here, unlike everywhere else in the app: a bench press works the chest whether
 * the load is a barbell, dumbbells or a Smith machine, so folding them together
 * makes the heat map right more often rather than less.
 */
const map = new Map();
const put = (key, groups, strong) => {
  if (!key) return;
  const had = map.get(key);
  // A name the coach would actually type (strong) always wins over a reduced form,
  // and the first reduced form wins over later ones, so "Squat" keeps meaning the
  // barbell squat rather than whatever squat variant came last in the dataset.
  if (had && (had.strong || !strong)) return;
  map.set(key, { groups, strong });
};

const named = (label) => ([name, id]) => {
  const e = byId.get(id);
  if (!e) { console.warn(`${label} points at a missing exercise: ${name} → ${id}`); return; }
  // Only the name as written is strong. Its reduced forms are no more trustworthy
  // than any other exercise's, so they must not outrank a real name.
  mapKeys(name).forEach((k, i) => put(k, musclesOf(e), i === 0));
};

// 1. Hand-added wordings first: they exist precisely to beat a wrong reduction.
Object.entries(synonyms || {}).forEach(named("synonym"));

// 2. Theryn's own names — what a coach picks from the picker, so the best keys.
Object.entries(aliases || {}).forEach(named("alias"));

// 3. Every dataset name.
for (const e of library) mapKeys(e.name).forEach((k, i) => put(k, musclesOf(e), i === 0));

const out = {};
for (const [k, v] of [...map.entries()].sort(([a], [b]) => a.localeCompare(b))) out[k] = v.groups;

const body = `// GENERATED by scripts/build-muscle-map.mjs — do not edit by hand.
//
// Exercise name → the muscle groups it works, most important first. Built from
// public/exercises.json (free-exercise-db, public domain) with the hand review of
// 2026-09-26, plus Theryn's own exercise names from scripts/theryn-exercise-aliases.json.
//
// Keys are already normalised by mapKeys() in src/lib/muscleHeat.js; look names up
// through musclesForExercise() there rather than reading this object directly.
// ${library.length} exercises, ${Object.keys(out).length} keys.

export const MUSCLE_MAP = ${JSON.stringify(out, null, 0)};

export default MUSCLE_MAP;
`;

const dest = path.join(root, "src/lib/muscleMap.generated.js");
fs.writeFileSync(dest, body);
console.log(`${library.length} exercises → ${Object.keys(out).length} keys, ${(body.length / 1024).toFixed(1)} KB → ${path.relative(root, dest)}`);
